"""Synthesizeable Verilog-2001 datapath and self-contained controller generators."""
from math import ceil,log2
from .ir import Design
from .scheduling import validate,latency
from .binding import bind

def step_width(cycles:int)->int:return max(1,(max(1,cycles)-1).bit_length())
def lit(d:Design,value:int)->str:return f"{d.width}'d{value & ((1<<d.width)-1)}"
def src(d:Design,a:str|int)->str:
    if isinstance(a,int):return lit(d,a)
    return f'i_{a}' if a in d.inputs else f'v_{a}'
def outs_units(b):return [f'fu_{op}_{u}_out' for op in ('add','sub','mul') for u in range(b['units'][op])]
def port_lines(d:Design,b,inputs_captured=False,controller=False):
    w=d.width; sw=step_width(latency(b['schedule']))
    ports=['input wire clk','input wire rst']
    if controller:ports+=['input wire start','input wire step_enable','output reg busy','output reg done',f'output wire [{sw-1}:0] step_debug']
    else:ports+=['input wire write_en',f'input wire [{sw-1}:0] step']
    for a in d.inputs:ports.append(f'input wire [{w-1}:0] {a if controller else "i_"+a}')
    for out in d.outputs:ports.append(f'output wire [{w-1}:0] {out}')
    for u in outs_units(b):ports.append(f'output wire [{w-1}:0] {u}')
    return ports

def datapath(d:Design,schedule:dict)->str:
    validate(d,schedule);b=bind(d,schedule);w=d.width
    ports=port_lines(d,b)
    ss=["// Generated by Fritz's EC551 PA2 backend; arithmetic is unsigned modulo 2**WIDTH.",
        "// Operations are 1-cycle combinational; register writes occur on the clock edge.",
        'module generated_datapath(', '    '+',\n    '.join(ports), ');',
        f'  // Schedule length: {latency(schedule)} cycles; resource binding is by operation type.']
    for n in d.nodes:ss.append(f'  reg [{w-1}:0] v_{n.id};')
    for out,source in d.outputs.items():ss.append(f'  assign {out} = {src(d,source)};')
    for unit,assignments in b['operand_muxes'].items():
        op,idx=unit.rsplit('_',1)
        for suffix,port_index in (('a',0),('b',1)):
            clauses=[f"(step == {step_width(latency(schedule))}'d{v['cycle']}) ? {src(d,v[suffix])}" for v in assignments]
            expr=' :\n      '.join(clauses+[f"{w}'d0"])
            ss.append(f'  wire [{w-1}:0] mux_{unit}_{suffix} =\n      {expr};')
        ss.append(f'  pa2_{op} #(.WIDTH({w})) unit_{unit} ('
                  f'.a(mux_{unit}_a), .b(mux_{unit}_b), .y(fu_{unit}_out));')
    ss+=['  always @(posedge clk) begin','    if (rst) begin']
    for n in d.nodes:ss.append(f"      v_{n.id} <= {w}'d0;")
    ss+=['    end else if (write_en) begin']
    cycle_to_nodes={t:[] for t in sorted(set(schedule.values()))}
    for n in d.nodes:cycle_to_nodes[schedule[n.id]].append(n.id)
    if d.nodes:
        ss.append('      case (step)')
        for t,nodes in cycle_to_nodes.items():
            ss.append(f"        {step_width(latency(schedule))}'d{t}: begin")
            for nid in nodes:ss.append(f"          v_{nid} <= fu_{b['assignment'][nid]['physical_unit']}_out;")
            ss.append('        end')
        ss+=['        default: begin end','      endcase']
    ss+=['    end','  end','endmodule','']
    return '\n'.join(ss)

def system(d:Design,schedule:dict)->str:
    validate(d,schedule);b=bind(d,schedule)
    count=latency(schedule);sw=step_width(count);w=d.width
    ports=port_lines(d,b,controller=True)
    s=["// Generated by Fritz's EC551 PA2 backend; internal controller can be replaced",
       "// with Ayla's FSM when integrated. Inputs are sampled at START.",
       "// step_enable MUST be a debounced one-clock pulse, synchronous to clk.",
       'module generated_system(', '    '+',\n    '.join(ports), ');',
       f'  reg [{sw-1}:0] step;', '  assign step_debug = step;']
    for a in d.inputs:s.append(f'  reg [{w-1}:0] input_latch_{a};')
    s+=['  generated_datapath dp (', '    .clk(clk), .rst(rst), .write_en(busy && step_enable), .step(step),']
    for a in d.inputs:s.append(f'    .i_{a}(input_latch_{a}),')
    for out in d.outputs:s.append(f'    .{out}({out}),')
    for j,u in enumerate(outs_units(b)):
        s.append(f'    .{u}({u})'+(',' if j<len(outs_units(b))-1 else ''))
    if not outs_units(b):
        # Remove trailing comma from final connected output (or step if empty).
        s[-1]=s[-1].rstrip(',')
    s+=['  );', '  always @(posedge clk) begin', '    if (rst) begin',
        "      busy <= 1'b0;", "      done <= 1'b0;",f"      step <= {sw}'d0;"]
    for a in d.inputs:s.append(f"      input_latch_{a} <= {w}'d0;")
    s+=['    end else if (start && !busy) begin',"      done <= 1'b0;",f"      step <= {sw}'d0;"]
    for a in d.inputs:s.append(f'      input_latch_{a} <= {a};')
    if count:
        s.append("      busy <= 1'b1;")
    else:
        s.append("      done <= 1'b1;")
    s+=['    end else if (busy && step_enable) begin']
    if count:
        s+= [f"      if (step == {sw}'d{count-1}) begin", "        busy <= 1'b0;", "        done <= 1'b1;",'      end else begin',
             f"        step <= step + {sw}'d1;",'      end']
    s+=['    end','  end','endmodule','']
    return '\n'.join(s)
