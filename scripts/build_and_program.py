#!/usr/bin/env python3
"""Fritz PA2: one command to compile equations and build/program with Vivado.

IMPORTANT: Ayla's board-level wrapper and *real board* constraints are required.
This script does not invent pins. --dry-run writes TCL without invoking Vivado.
A successful script run with --dry-run is NOT FPGA verification.
"""
from __future__ import annotations
import argparse
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from hls.cli import main as hls_main


def tcl_string(path: Path) -> str:
    s = str(path.resolve()).replace('\\', '/')
    # Tcl brace quoting protects spaces, $ and square brackets in Windows paths.
    if '}' in s or '{' in s:
        raise ValueError('paths containing braces are unsupported by the TCL generator')
    return '{' + s + '}'


def generate_tcl(sources: list[Path], xdc: Path, part: str, top: str,
                 bitstream: Path, program: bool, device: str | None) -> str:
    lines = ['# Generated by EC551 PA2 Fritz: synthesis / implementation / optional programming',
             '# Hardware I/O configuration belongs to the supplied board wrapper and XDC.']
    for file in sources:
        lines.append(f'read_verilog {tcl_string(file)}')
    lines += [f'read_xdc {tcl_string(xdc)}',
              f'synth_design -top {top} -part {part}',
              'opt_design', 'place_design', 'route_design',
              f'report_timing_summary -file {tcl_string(bitstream.with_suffix(".timing.rpt"))}',
              f'report_utilization -file {tcl_string(bitstream.with_suffix(".utilization.rpt"))}',
              f'write_bitstream -force {tcl_string(bitstream)}']
    if program:
        lines += ['open_hw_manager', 'connect_hw_server', 'open_hw_target',
                  f'set devices [get_hw_devices {device}]' if device else 'set devices [get_hw_devices]',
                  'if {[llength $devices] != 1} {error "Expected exactly one matching FPGA; use --hw-device"}',
                  'set hw_device [lindex $devices 0]',
                  'current_hw_device $hw_device', 'refresh_hw_device $hw_device',
                  f'set_property PROGRAM.FILE {tcl_string(bitstream)} $hw_device',
                  'program_hw_devices $hw_device', 'close_hw_manager']
    return '\n'.join(lines) + '\n'


def main(argv=None):
    p = argparse.ArgumentParser(description='Equation file -> RTL -> Vivado bitstream -> optionally program board')
    p.add_argument('--equations', type=Path, required=True, help='Ayla-format text equation file')
    p.add_argument('--scheduler', default='custom', choices=['asap','alap','cons-alap','custom','cons-asap'])
    p.add_argument('--adders', type=int, default=1)
    p.add_argument('--subs', type=int, default=1)
    p.add_argument('--muls', type=int, default=1)
    p.add_argument('--latency', type=int, help='ALAP deadline, cycles')
    p.add_argument('--width', type=int, default=8)
    p.add_argument('--test-values', default=None, help='e.g. A=3,B=2')
    p.add_argument('--board-top', type=Path, default=None,
                   help='board wrapper Verilog (default: the generated fpga_top.v for the Nexys4 DDR)')
    p.add_argument('--xdc', type=Path, default=ROOT / 'rtl' / 'nexys4ddr.xdc',
                   help='board constraints (default: rtl/nexys4ddr.xdc)')
    p.add_argument('--part', default='xc7a100tcsg324-1', help='Xilinx part (default: Nexys4 DDR xc7a100tcsg324-1)')
    p.add_argument('--top', default='fpga_top', help='top module name (default: fpga_top)')
    p.add_argument('--additional-verilog', type=Path, nargs='*', default=[], help='extra modules the board wrapper uses')
    p.add_argument('--out', type=Path, default=Path('out/fpga_build'))
    p.add_argument('--vivado', default='vivado', help='vivado or full path to vivado.bat')
    p.add_argument('--program', action='store_true', help='also program the connected board (default: build bitstream only)')
    p.add_argument('--hw-device', default=None, help='specific name/pattern of target device on JTAG chain')
    p.add_argument('--dry-run', action='store_true', help='generate RTL and Vivado TCL; do not synthesize/program')
    a = p.parse_args(argv)
    for file in [a.equations, a.xdc, *([a.board_top] if a.board_top else []), *a.additional_verilog]:
        if not file.is_file():
            p.error(f'missing input file: {file}')
    if not 1 <= a.width <= 64:
        p.error('--width must be 1..64')
    if any(x < 1 for x in (a.adders, a.subs, a.muls)):
        p.error('unit counts must be positive')
    if not a.part.strip() or not a.top.isidentifier():
        p.error('invalid part or top module name')
    folder = a.out.resolve()
    hls_out = folder / 'generated'
    args = [str(a.equations.resolve()), '--schedule', a.scheduler,
            '--width', str(a.width), '--out', str(hls_out), '--emit-rtl',
            '--adders', str(a.adders), '--subs', str(a.subs), '--muls', str(a.muls)]
    if a.scheduler in ('asap', 'alap'):
        # Unconstrained algorithms should receive no hardware limits.
        for flag in ('--adders','--subs','--muls'):
            i = args.index(flag); del args[i:i+2]
    if a.latency is not None:
        args += ['--latency', str(a.latency)]
    if a.test_values is not None:
        args += ['--test-values', a.test_values]
    print('Compiling equations using the shared hls pipeline...', flush=True)
    result = hls_main(args)
    if result != 0:
        return result
    stem = a.equations.stem
    rtl_dir = hls_out / f'{stem}_{a.scheduler}_rtl'
    rtl_sources = [rtl_dir / x for x in ('functional_units.v', 'generated_datapath.v', 'generated_system.v',
                                         'board_helpers.v')]
    board_top = a.board_top or rtl_dir / 'fpga_top.v'
    bitstream = folder / (a.top + '.bit')
    folder.mkdir(parents=True, exist_ok=True)
    tcl_file = folder / 'build_and_program.tcl'
    text = generate_tcl(rtl_sources + [board_top, *a.additional_verilog],
                        a.xdc, a.part, a.top, bitstream, a.program, a.hw_device)
    tcl_file.write_text(text, encoding='utf-8')
    print('Build TCL:', tcl_file)
    if a.dry_run:
        print('DRY RUN only: RTL and TCL generated; NO Vivado synthesis, routing, bitstream, or FPGA programming occurred.')
        return 0
    executable = shutil.which(a.vivado) or (a.vivado if Path(a.vivado).is_file() else None)
    if not executable:
        print('ERROR: Vivado executable unavailable; pass --vivado with its Windows path.', file=sys.stderr)
        return 2
    cmd = [executable, '-mode', 'batch', '-source', str(tcl_file), '-log',
           str(folder / 'vivado.log'), '-journal', str(folder / 'vivado.jou')]
    print('Executing:', cmd, flush=True)
    proc = subprocess.run(cmd, cwd=ROOT, check=False)
    if proc.returncode:
        print('ERROR: Vivado failed. Read vivado.log for details.', file=sys.stderr)
        return proc.returncode
    if not bitstream.exists():
        print('ERROR: Vivado exited but no .bit file was produced.', file=sys.stderr)
        return 3
    print('Bitstream produced:', bitstream)
    if a.program:
        print('Vivado programming command completed; verify behavior on physical hardware.')
    else:
        print('No board programming requested; pass --program after verifying board and I/O.')
    return 0

if __name__ == '__main__':
    raise SystemExit(main())
